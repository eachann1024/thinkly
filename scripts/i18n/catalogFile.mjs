import { relative, resolve, dirname } from "node:path";
import MagicString from "magic-string";
import { extractBlocks } from "./compiler.mjs";
import { parseMessages } from "./validate.mjs";

const quote = JSON.stringify;
function schemaType(schema) {
  return `{ ${Object.entries(schema).map(([key, params]) => `${quote(key)}: { ${Object.entries(params).map(([name, type]) => `${quote(name)}: ${type}`).join("; ")} }`).join("; ")} }`;
}

export function analyzeCatalogFile(root, filename, code, metrics) {
  const source = relative(root, filename).replaceAll("\\", "/");
  const record = { source, code, normalizedCode: code, entries: [], declarations: [], sidecar: null };
  if (/\.ya?ml$/.test(filename)) {
    if (metrics) metrics.parsedFiles++;
    const parsed = parseMessages(code, source);
    record.entries.push({ ...parsed, source, line: 1, name: "default", context: code });
    let typesImport = relative(dirname(filename), resolve(root, "src/i18n/types")).replaceAll("\\", "/");
    if (!typesImport.startsWith(".")) typesImport = `./${typesImport}`;
    record.sidecar = `// Generated by scripts/i18n/check.mjs --generate.\nimport type { CompiledMessages } from ${quote(typesImport)};\ndeclare const messages: CompiledMessages<${schemaType(parsed.schema)}>;\nexport default messages;\n`;
    return record;
  }
  if (!code.includes("i18n")) return record;
  if (metrics) { metrics.parsedFiles++; metrics.typePrograms++; }
  const { blocks } = extractBlocks(code, source);
  const output = new MagicString(code);
  for (const [index, block] of blocks.entries()) {
    const id = `${source}#${block.name}:${index + 1}`;
    record.declarations.push(`    ${quote(id)}: ${schemaType(block.schema)};`);
    const annotation = `<${quote(id)}>`;
    if (block.node.tag.end === block.node.template.getStart()) output.appendLeft(block.node.tag.end, annotation);
    else output.overwrite(block.node.tag.end, block.node.template.getStart(), annotation);
    record.entries.push({ resources: block.resources, schema: block.schema, source, line: block.line, name: block.name, id, context: code });
  }
  record.normalizedCode = output.toString();
  return record;
}
