import { readdir, readFile, writeFile, access, unlink, mkdir } from "node:fs/promises";
import { relative, resolve, dirname } from "node:path";
import MagicString from "magic-string";
import { extractBlocks } from "./compiler.mjs";
import { parseMessages } from "./validate.mjs";

export async function collectFiles(root) {
  const results = [];
  async function walk(directory) {
    for (const entry of await readdir(directory, { withFileTypes: true })) {
      const filename = resolve(directory, entry.name);
      if (entry.isDirectory()) await walk(filename);
      else if ((/\.(?:[jt]sx?|ya?ml)$/.test(entry.name) && !/\.d\.ts$/.test(entry.name)) || /\.ya?ml\.d\.ts$/.test(entry.name)) results.push(filename);
    }
  }
  await walk(resolve(root, "src"));
  await walk(resolve(root, "electron"));
  return results.sort();
}
const quote = JSON.stringify;
function schemaType(schema) {
  return `{ ${Object.entries(schema).map(([key, params]) => `${quote(key)}: { ${Object.entries(params).map(([name, type]) => `${quote(name)}: ${type}`).join("; ")} }`).join("; ")} }`;
}
async function syncFile(filename, content, generate, stale) {
  const before = await readFile(filename, "utf8").catch((error) => { if (error.code === "ENOENT") return ""; throw error; });
  if (before === content) return;
  if (generate) await writeFile(filename, content);
  else stale.push(filename);
}

export async function collectCatalog(root, generate) {
  const entries = [], stale = [], codeFiles = [], declarations = [];
  for (const filename of await collectFiles(root)) {
    const source = relative(root, filename).replaceAll("\\", "/");
    const code = await readFile(filename, "utf8");
    if (/\.ya?ml\.d\.ts$/.test(filename)) {
      const sourceExists = await access(filename.slice(0, -5)).then(() => true, (error) => {
        if (error.code === "ENOENT") return false;
        throw error;
      });
      if (!sourceExists && code.startsWith("// Generated by scripts/i18n/check.mjs")) {
        if (generate) await unlink(filename); else stale.push(filename);
      }
      continue;
    }
    if (/\.ya?ml$/.test(filename)) {
      const parsed = parseMessages(code, source);
      entries.push({ ...parsed, source, line: 1, name: "default", context: code });
      let typesImport = relative(dirname(filename), resolve(root, "src/i18n/types")).replaceAll("\\", "/");
      if (!typesImport.startsWith(".")) typesImport = `./${typesImport}`;
      const declaration = `// Generated by scripts/i18n/check.mjs --generate.\nimport type { CompiledMessages } from ${quote(typesImport)};\ndeclare const messages: CompiledMessages<${schemaType(parsed.schema)}>;\nexport default messages;\n`;
      await syncFile(`${filename}.d.ts`, declaration, generate, stale);
      continue;
    }
    codeFiles.push({ source, code });
    if (!code.includes("i18n")) continue;
    const { blocks } = extractBlocks(code, source);
    const output = new MagicString(code);
    for (const [index, block] of blocks.entries()) {
      const id = `${source}#${block.name}:${index + 1}`;
      declarations.push(`    ${quote(id)}: ${schemaType(block.schema)};`);
      const annotation = `<${quote(id)}>`;
      if (block.node.tag.end === block.node.template.getStart()) output.appendLeft(block.node.tag.end, annotation);
      else output.overwrite(block.node.tag.end, block.node.template.getStart(), annotation);
      entries.push({ resources: block.resources, schema: block.schema, source, line: block.line, name: block.name, id, context: code });
    }
    if (blocks.length) await syncFile(filename, output.toString(), generate, stale);
  }
  const generatedDirectory = resolve(root, "src/i18n/generated");
  const generatedHeader = "// Generated by scripts/i18n/check.mjs --generate. Do not edit.";
  if (generate) await mkdir(generatedDirectory, { recursive: true });
  const chunks = [];
  for (let index = 0; index < declarations.length; index += 120) {
    const name = `catalog-${String(chunks.length + 1).padStart(3, "0")}.d.ts`;
    chunks.push(name);
    const content = `${generatedHeader}\nimport "../types";\ndeclare module "../types" {\n  interface MessageCatalog {\n${declarations.slice(index, index + 120).join("\n")}\n  }\n}\n`;
    await syncFile(resolve(generatedDirectory, name), content, generate, stale);
  }
  const existing = await readdir(generatedDirectory).catch((error) => {
    if (error.code === "ENOENT") return [];
    throw error;
  });
  for (const name of existing) {
    if (!/^catalog-\d+\.d\.ts$/.test(name) || chunks.includes(name)) continue;
    const filename = resolve(generatedDirectory, name);
    if (!(await readFile(filename, "utf8")).startsWith(generatedHeader)) continue;
    if (generate) await unlink(filename); else stale.push(filename);
  }
  const content = `${generatedHeader}\n${chunks.map((name) => `import "./generated/${name.slice(0, -5)}";`).join("\n")}\n`;
  await syncFile(resolve(root, "src/i18n/catalog.generated.d.ts"), content, generate, stale);
  return { entries, stale, codeFiles };
}
