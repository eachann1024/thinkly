import { readdir, readFile, writeFile, unlink, mkdir } from "node:fs/promises";
import { relative, resolve } from "node:path";
import { analyzeCatalogFile } from "./catalogFile.mjs";

const GENERATED_HEADER = "// Generated by scripts/i18n/check.mjs --generate. Do not edit.";
const YAML_HEADER = "// Generated by scripts/i18n/check.mjs";
export const catalogSource = (file) => /\.(?:[jt]sx?|ya?ml)$/.test(file) && !/\.d\.ts$/.test(file);
export function catalogPath(root, file) {
  const source = relative(root, resolve(root, file)).replaceAll("\\", "/");
  return /^(?:src|electron)\//.test(source) && catalogSource(file);
}
export function createCatalogMetrics() {
  return { sourceReads: 0, parsedFiles: 0, typePrograms: 0, writes: 0, cacheHits: 0, directoryReads: 0, publications: 0 };
}
export async function collectFiles(root, metrics) {
  const results = [];
  async function walk(directory) {
    if (metrics) metrics.directoryReads++;
    for (const entry of await readdir(directory, { withFileTypes: true })) {
      const filename = resolve(directory, entry.name);
      if (entry.isDirectory()) await walk(filename);
      else if (catalogSource(entry.name) || /\.ya?ml\.d\.ts$/.test(entry.name)) results.push(filename);
    }
  }
  await walk(resolve(root, "src"));
  await walk(resolve(root, "electron"));
  return results.sort();
}
export async function readOptional(filename) {
  return readFile(filename, "utf8").catch((error) => {
    if (error.code === "ENOENT") return null;
    throw error;
  });
}
async function syncFile(filename, content, generate, stale, metrics, expected) {
  const before = await readOptional(filename);
  if (before === content) return;
  if (expected !== undefined && before !== expected) {
    const error = new Error(`${filename}: source changed while generating its i18n annotation`);
    error.code = "CATALOG_SOURCE_CHANGED";
    throw error;
  }
  if (generate) { await writeFile(filename, content); if (metrics) metrics.writes++; }
  else stale.push(filename);
}
export async function removeYamlDeclaration(filename, generate, stale, metrics) {
  const declaration = `${filename}.d.ts`;
  if (!(await readOptional(declaration))?.startsWith(YAML_HEADER)) return;
  if (generate) { await unlink(declaration); if (metrics) metrics.writes++; }
  else stale.push(declaration);
}
export async function readCatalogFile(root, filename, generate, stale, metrics, previous) {
  if (metrics) metrics.sourceReads++;
  const code = await readOptional(filename);
  if (code === null) {
    if (/\.ya?ml$/.test(filename)) await removeYamlDeclaration(filename, generate, stale, metrics);
    return null;
  }
  if (previous?.normalizedCode === code) {
    if (metrics) metrics.cacheHits++;
    if (previous.sidecar) await syncFile(`${filename}.d.ts`, previous.sidecar, generate, stale, metrics);
    return previous;
  }
  const record = analyzeCatalogFile(root, filename, code, metrics);
  if (record.sidecar) await syncFile(`${filename}.d.ts`, record.sidecar, generate, stale, metrics);
  if (record.normalizedCode !== code) await syncFile(filename, record.normalizedCode, generate, stale, metrics, code);
  return record;
}
export async function publishCatalog(root, records, generate, stale, metrics, outputs) {
  if (metrics) metrics.publications++;
  const live = new Set();
  const syncOutput = (filename, content) => {
    live.add(filename); outputs?.set(filename, content);
    return syncFile(filename, content, generate, stale, metrics);
  };
  const ordered = [...records.values()].sort((a, b) => a.source < b.source ? -1 : a.source > b.source ? 1 : 0);
  const declarations = ordered.flatMap((record) => record.declarations);
  const generatedDirectory = resolve(root, "src/i18n/generated");
  if (generate) await mkdir(generatedDirectory, { recursive: true });
  const chunks = [];
  for (let index = 0; index < declarations.length; index += 120) {
    const name = `catalog-${String(chunks.length + 1).padStart(3, "0")}.d.ts`;
    chunks.push(name);
    const content = `${GENERATED_HEADER}\nimport "../types";\ndeclare module "../types" {\n  interface MessageCatalog {\n${declarations.slice(index, index + 120).join("\n")}\n  }\n}\n`;
    await syncOutput(resolve(generatedDirectory, name), content);
  }
  const existing = await readdir(generatedDirectory).catch((error) => {
    if (error.code === "ENOENT") return [];
    throw error;
  });
  for (const name of existing) {
    if (!/^catalog-\d+\.d\.ts$/.test(name) || chunks.includes(name)) continue;
    const filename = resolve(generatedDirectory, name);
    if (!(await readFile(filename, "utf8")).startsWith(GENERATED_HEADER)) continue;
    if (generate) { await unlink(filename); outputs?.delete(filename); if (metrics) metrics.writes++; } else stale.push(filename);
  }
  const content = `${GENERATED_HEADER}\n${chunks.map((name) => `import "./generated/${name.slice(0, -5)}";`).join("\n")}\n`;
  await syncOutput(resolve(root, "src/i18n/catalog.generated.d.ts"), content);
  if (outputs) for (const filename of outputs.keys()) if (!live.has(filename)) outputs.delete(filename);
  return { entries: ordered.flatMap((record) => record.entries), stale,
    codeFiles: ordered.filter((record) => !record.sidecar).map(({ source, code }) => ({ source, code })) };
}

/** CLI always performs a full scan; only the Vite session keeps incremental state. */
export async function collectCatalog(root, generate) {
  const records = new Map(), stale = [];
  for (const filename of await collectFiles(root)) {
    if (/\.ya?ml\.d\.ts$/.test(filename)) {
      if (await readOptional(filename.slice(0, -5)) === null) await removeYamlDeclaration(filename.slice(0, -5), generate, stale);
      continue;
    }
    const record = await readCatalogFile(root, filename, generate, stale);
    if (record) records.set(filename, record);
  }
  return publishCatalog(root, records, generate, stale);
}
