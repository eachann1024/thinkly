import { relative, resolve } from "node:path";
import {
  catalogPath, collectFiles, createCatalogMetrics, publishCatalog,
  readCatalogFile, readOptional, removeYamlDeclaration,
} from "./catalog.mjs";
import { createGenerationQueue } from "./catalogQueue.mjs";

export function createCatalogSession(root) {
  root = resolve(root);
  let records = new Map(), initialized = false;
  const outputs = new Map();
  const globalOutput = (filename) => /^src\/i18n\/(?:catalog\.generated\.d\.ts|generated\/catalog-\d+\.d\.ts)$/.test(relative(root, filename).replaceAll("\\", "/"));
  const metrics = createCatalogMetrics();
  const queue = createGenerationQueue(async (paths) => {
    const full = !initialized || paths === null;
    const files = full ? await collectFiles(root, metrics) : paths;
    const delta = new Map();
    const stale = [];
    let changed = full;
    try {
      for (const file of files) {
        const filename = resolve(root, file);
        if (!full && globalOutput(filename)) { changed = true; continue; }
        if (/\.ya?ml\.d\.ts$/.test(filename)) {
          if (full && await readOptional(filename.slice(0, -5)) === null) {
            await removeYamlDeclaration(filename.slice(0, -5), true, stale, metrics);
          }
          continue;
        }
        if (!catalogPath(root, filename)) continue;
        const previous = records.get(filename);
        const record = await readCatalogFile(root, filename, true, stale, metrics, previous);
        if (full || record !== previous) delta.set(filename, record);
        if (JSON.stringify(record?.declarations ?? []) !== JSON.stringify(previous?.declarations ?? [])) changed = true;
      }
    } catch (error) {
      if (error.code !== "CATALOG_SOURCE_CHANGED") throw error;
      void queue.request(full ? null : files).catch(() => undefined);
      return;
    }
    const next = full ? new Map() : changed ? new Map(records) : records;
    for (const [filename, record] of delta) {
      if (record) next.set(filename, record); else next.delete(filename);
    }
    if (changed) await publishCatalog(root, next, true, stale, metrics, outputs);
    records = next; initialized = true;
  });
  return {
    metrics, queueMetrics: queue.metrics,
    async refresh(paths = null) {
      const relevant = [];
      for (const file of paths ?? []) {
        const filename = resolve(root, file);
        if (catalogPath(root, filename)) relevant.push(filename);
        else if (/\.ya?ml\.d\.ts$/.test(filename) && catalogPath(root, filename.slice(0, -5))) relevant.push(filename.slice(0, -5));
        else if (globalOutput(filename)) {
          const current = await readOptional(filename);
          if (outputs.has(filename) ? current !== outputs.get(filename) : current?.startsWith("// Generated by scripts/i18n/check.mjs")) relevant.push(filename);
        }
      }
      if (paths !== null && relevant.length === 0 && initialized) return;
      return queue.request(initialized && paths !== null ? relevant : null);
    },
    close: () => queue.close(),
  };
}
